#!/usr/bin/env bash
# Shared Ubuntu setup helpers. Source this file from a setup entry point.

fail() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

run() {
    printf '+'
    printf ' %q' "$@"
    printf '\n'
    if (( ! SETUP_DRY_RUN )); then
        "$@"
    fi
}

setup_init() {
    SETUP_ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
    SETUP_PREFIX="$SETUP_ROOT/.local"
    SETUP_DRY_RUN=0
    while (( $# )); do
        case "$1" in
            --dry-run) SETUP_DRY_RUN=1; shift ;;
            --prefix)
                (( $# >= 2 )) && [[ -n "$2" && "$2" != --* ]] || fail '--prefix requires a directory'
                SETUP_PREFIX=$2
                shift 2
                ;;
            -h|--help)
                printf '%s\n\nUsage: bash %s [--dry-run] [--prefix DIR]\n' "$SETUP_DESCRIPTION" "$0"
                printf 'Default directory: %s/.local\n' "$SETUP_ROOT"
                exit 0
                ;;
            *) fail "unknown argument: $1 (see --help)" ;;
        esac
    done
    [[ $(uname -s) == Linux ]] || fail 'Ubuntu on Linux or WSL is required'
    local ID='' VERSION_ID=''
    # shellcheck source=/dev/null
    source /etc/os-release
    [[ "$ID" == ubuntu ]] || fail 'Ubuntu 22.04 or later is required (including Ubuntu on WSL)'
    dpkg --compare-versions "$VERSION_ID" ge 22.04 || fail 'Ubuntu 22.04 or later is required'
    SETUP_PREFIX=$(realpath -m -- "$SETUP_PREFIX")
}

require_command() {
    command -v "$1" >/dev/null || fail "missing command: $1; run tools/setup/common.sh first"
}

require_file() {
    if (( ! SETUP_DRY_RUN )); then
        [[ -f "$1" ]] || fail "missing SDK file: $1"
    fi
}

# Clone into a temporary sibling so an interrupted download can be retried.
# Existing checkouts are checked, never reset or updated to another version.
install_sdk() (
    local url=$1 tag=$2 destination=$3
    shift 3
    local temporary head expected status
    if [[ -e "$destination" ]]; then
        [[ -d "$destination/.git" ]] || fail "SDK directory already exists and is not a managed Git checkout: $destination; use another --prefix"
        [[ $(git -C "$destination" config --get remote.origin.url) == "$url" ]] || fail "unexpected SDK origin: $destination"
        head=$(git -C "$destination" rev-parse HEAD)
        expected=$(git -C "$destination" rev-parse --verify "refs/tags/$tag^{commit}") || fail "SDK tag $tag is missing: $destination"
        [[ "$head" == "$expected" ]] || fail "SDK is not at $tag: $destination"
        [[ -z $(git -C "$destination" status --porcelain --untracked-files=no) ]] || fail "SDK has local changes: $destination"
        if (( $# )); then
            status=$(git -C "$destination" submodule status -- "$@")
            if [[ "$status" =~ (^|$'\n')[-+U] ]]; then
                fail "SDK submodules are incomplete or changed: $destination"
            fi
        fi
        printf 'Using existing SDK: %s (%s)\n' "$destination" "$tag"
        exit 0
    fi
    if (( SETUP_DRY_RUN )); then
        run git clone --depth 1 --branch "$tag" --single-branch -- "$url" "$destination"
        if (( $# )); then
            run git -C "$destination" submodule update --init --depth 1 -- "$@"
        fi
        exit 0
    fi
    mkdir -p -- "$(dirname -- "$destination")"
    temporary=$(mktemp -d "$(dirname -- "$destination")/.sdk-XXXXXX")
    trap 'rm -rf -- "$temporary"' EXIT
    run git clone --depth 1 --branch "$tag" --single-branch -- "$url" "$temporary/sdk"
    if (( $# )); then
        run git -C "$temporary/sdk" submodule update --init --depth 1 -- "$@"
    fi
    mv -T -- "$temporary/sdk" "$destination"
)

# Each setup owns one fragment; the loader preserves other board setups.
write_environment() (
    local profile=$1
    shift
    local fragment="$SETUP_PREFIX/env.d/$profile.sh" temporary key value file
    if (( SETUP_DRY_RUN )); then
        printf 'Would write %s and %s/env.sh\n' "$fragment" "$SETUP_PREFIX"
        while (( $# )); do
            printf '  export %s=%q\n' "$1" "$2"
            shift 2
        done
        exit 0
    fi
    mkdir -p -- "$SETUP_PREFIX/env.d"
    temporary=$(mktemp "$SETUP_PREFIX/env.d/.env-XXXXXX")
    trap 'rm -f -- "$temporary"' EXIT
    {
        printf '# Generated by emelino setup. Load env.sh from Bash.\n'
        while (( $# )); do
            key=$1 value=$2
            shift 2
            printf 'export %s=%q\n' "$key" "$value"
        done
        if [[ "$profile" == common ]]; then
            printf 'export PATH=%q:"$PATH"\n' "$SETUP_CARGO_BIN"
        fi
    } > "$temporary"
    mv -f -- "$temporary" "$fragment"
    temporary=$(mktemp "$SETUP_PREFIX/.env-XXXXXX")
    {
        printf '# Generated by emelino setup.\n'
        for profile in common nucleo-f446re arduino-nano-33-ble; do
            file="$SETUP_PREFIX/env.d/$profile.sh"
            printf 'if [[ -f %q ]]; then source %q; fi\n' "$file" "$file"
        done
    } > "$temporary"
    mv -f -- "$temporary" "$SETUP_PREFIX/env.sh"
)

setup_finished() {
    if (( SETUP_DRY_RUN )); then
        printf '\nDry run complete; no packages or files were changed.\n'
    else
        printf '\nSetup complete. Load the environment in this terminal:\n  source %q\n' "$SETUP_PREFIX/env.sh"
    fi
}
