"""Scenario steps and assertions; execution is provided by the common runner."""
import re
from support.common import build_firmware, renode_workspace, run_renode, value


def test(args, report):
    output, renode, manifest, symbols = build_firmware(args, report, "uart")
    report.update({"board": manifest["board"], "resources": manifest["resources"],
                   "firmware_sha256": manifest["sha256"]["firmware.bin"],
                   "compiler": manifest["compiler"], "sdk": manifest["sdk"]})
    report["model"] = "Renode generic STM32F4, USART2 on PA2/PA3, F446RE memory sizes"
    report["model_limitations"] = ["not an STM32F446 silicon model",
        "UART backend is byte-oriented; 9-bit TX is observed at DR writes and RX bit 8 is injected at DR reads",
        "CR1.M, PEIE and CR3.EIE are not modeled; their requested writes are recorded",
        "PE/FE/NE/ORE are injected into SR reads, not generated by an electrical serial waveform",
        "baud accuracy, line timing, CTS/RTS and electrical behavior are not validated"]
    args.platform.prepare(renode, output, report)
    with renode_workspace(output) as (alias, temporary):
        (output / "machine.repl").write_text(args.platform.machine_header(alias) +
            'syscfg: Memory.MappedMemory @ sysbus 0x40013800\n    size: 0x400\n')
        script = [f'logFile @{alias}/model.log', 'logLevel 1 file', 'logLevel 3 console',
                  'mach create', f'machine LoadPlatformDescription @{alias}/machine.repl',
                  args.platform.load_binary(alias),
                  'sysbus.cpu PerformanceInMips 100',
                  f'sysbus.usart2 CreateFileBackend @{alias}/uart.log true',
                  'sysbus SetHookBeforePeripheralWrite sysbus.usart2 "self.Log(LogLevel.Info, \'UART_WRITE offset={0} value={1}\', offset, value)"',
                  'sysbus.cpu Reset']

        def advance(duration="0:00:00.001"):
            script.append(f'emulation RunFor "{duration}"')

        def metric(label, address):
            script.extend([f'echo "{label}"', f'sysbus ReadDoubleWord 0x{address:x}'])

        def stage(number):
            metric(f"UART_STAGE_{number}", symbols["uart_test_stage"])
            metric(f"UART_FAILURES_{number}", symbols["uart_test_failures"])

        def resume(number):
            script.append(f'sysbus WriteDoubleWord 0x{symbols["uart_test_command"]:x} {number}')
            advance()

        def receive(byte):
            script.append(f'sysbus.usart2 WriteChar {byte}')
            advance()

        advance("0:00:00.004")
        stage(1)
        resume(1)
        receive(97)
        receive(98)
        stage(2)
        resume(2)
        receive(99)
        advance("0:00:00.008")
        stage(3)
        for byte in [100, 101, 102]:
            receive(byte)
        resume(3)
        stage(4)
        for byte in [103, 104, 105]:
            receive(byte)
        resume(4)
        stage(5)
        resume(5)
        receive(106)
        stage(6)
        for byte in range(65):
            receive(byte)
        resume(6)
        advance("0:00:00.008")
        for number, flags in [(7, 1), (8, 2), (9, 4), (10, 8)]:
            stage(number)
            script.append(f'sysbus SetHookAfterPeripheralRead sysbus.usart2 "if offset == 0: value |= {flags}"')
            receive(80 + number)
            script.append('sysbus SetHookAfterPeripheralRead sysbus.usart2 ""')
            resume(number)
        stage(11)
        receive(90)
        resume(11)
        stage(12)
        script.append('sysbus SetHookAfterPeripheralRead sysbus.usart2 "if offset == 4: value |= 256"')
        receive(255)
        resume(12)
        script.append('sysbus SetHookAfterPeripheralRead sysbus.usart2 ""')
        advance("0:00:00.008")
        names = ["uart_test_checks", "uart_test_failures", "uart_test_last_failure",
                 "emela_board_completed", "emela_board_failures", "emela_board_boot_initialized"]
        for name in names:
            metric("UART_FINAL_" + name, symbols[name])
        for label, address in {"MODER": 0x40020000, "AFRL": 0x40020020,
                               "BRR": 0x40004408, "CR1": 0x4000440c,
                               "RCC_APB1ENR": 0x40023840}.items():
            metric("UART_REGISTER_" + label, address)
        script.append('quit')
        status, log = run_renode(renode, output, alias, temporary, script, report, args.timeout)
    model_log = (output / "model.log").read_text(encoding="utf-8-sig")
    warning = r"^.*\[WARNING\] usart2: Unhandled write to offset "
    known_warning = re.compile(warning + r"(?:"
        r"0x0\. Unhandled bits: \[0-2, 8-31\] when writing value 0xFFFFFFBF\. Tags: PE \(0x1\), FE \(0x1\), NF \(0x1\), LBD \(0x1\), CTS \(0x1\), RESERVED \(0x3FFFFF\)\."
        r"|0xC\. Unhandled bits: \[8\] when writing value 0x[0-9A-F]+\. Tags: PEIE \(0x1\)\."
        r"|0xC\. Unhandled bits: \[12\] when writing value 0x[0-9A-F]+\. Tags: M \(0x1\)\."
        r"|0x14\. Unhandled bits: \[0\] when writing value 0x1\. Tags: EIE \(0x1\)\."
        r")\s*$", re.M)
    report["known_model_warnings"] = [line.strip() for line in known_warning.findall(model_log)]
    if status or re.search(r"\[(?:ERROR|WARNING)\]|There was an error executing command|Unhandled Exception", known_warning.sub("", log + model_log)):
        raise ValueError(f"Renode failed or warned; see {output / 'renode.log'} and model.log")
    stages = [value(log, f"UART_STAGE_{number}") for number in range(1, 13)]
    if stages != list(range(1, 13)):
        raise ValueError(f"UART did not reach the expected stages: {stages}")
    metrics = {name: value(log, "UART_FINAL_" + name) for name in names}
    expected = {"uart_test_checks": 33, "uart_test_failures": 0, "uart_test_last_failure": 0,
                "emela_board_completed": 1, "emela_board_failures": 0, "emela_board_boot_initialized": 1}
    if metrics != expected:
        raise ValueError(f"UART firmware checks failed: {metrics}")
    written_words = [int(word) for word in re.findall(r"UART_WRITE offset=4 value=(\d+)", model_log)]
    expected_words = [65, 66, 10, 73, 82, 81, 10, 0, 255, 256, 511, 127, 255]
    if written_words != expected_words:
        raise ValueError(f"UART DR writes differ (including width validation): {written_words}")
    cr1_writes = [int(word) for word in re.findall(r"UART_WRITE offset=12 value=(\d+)", model_log)]
    cr3_writes = [int(word) for word in re.findall(r"UART_WRITE offset=20 value=(\d+)", model_log)]
    if not any(word & 0x1000 for word in cr1_writes) or not any(word & 0x100 for word in cr1_writes) or not any(word & 1 for word in cr3_writes):
        raise ValueError("9-bit, parity error IRQ or error IRQ configuration was not requested")
    actual = (output / "uart.log").read_bytes()
    expected_bytes = bytes(word & 255 for word in expected_words)
    if actual != expected_bytes:
        raise ValueError(f"UART backend output differs: {actual!r} != {expected_bytes!r}")
    if (value(log, "UART_REGISTER_MODER") >> 4) & 15 != 10:
        raise ValueError("UART pins are not alternate-function outputs")
    if (value(log, "UART_REGISTER_AFRL") >> 8) & 255 != 0x77:
        raise ValueError("UART pins are not AF7")
    if value(log, "UART_REGISTER_BRR") != 139 or not value(log, "UART_REGISTER_RCC_APB1ENR") & (1 << 17):
        raise ValueError("incorrect baud divider or disabled USART2 clock")
    if value(log, "UART_REGISTER_CR1") & 0x3fff != 0x200c:
        raise ValueError("UART final 8N1 TX/RX configuration or IRQ disable differs")
    report.update({"status": "passed", "metrics": metrics, "stages": stages,
                   "transmitted_words": written_words, "uart_bytes_hex": actual.hex(),
                   "injected_errors": ["parity", "framing", "noise", "hardware overrun"],
                   "software_overflow_words": 65, "irq_ring_capacity": 64})
